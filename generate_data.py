def difficulty(score_gap, tier):
    """按相对国家线的超出幅度 + 层次给难度星级。"""
    if score_gap >= 42 or tier == "985":
        return 5
    if score_gap >= 28 or tier == "211":
        return 4
    if score_gap >= 16:
        return 3
    if score_gap >= 7:
        return 2
    return 1


def generate():
    rows = []
    header = ["学校", "省份", "城市", "层次", "专业", "专业代码", "门类",
              "初试科目", "复试线", "录取均分", "报录比", "招生人数", "难度"]

    # 门类 -> 学科代码前缀（示例，取常见口径）
    category_code = {
        "哲学": "0101", "经济学": "0202", "法学": "0301", "教育学": "0401",
        "文学": "0501", "历史学": "0601", "理学": "0701", "工学": "0812",
        "农学": "0901", "医学": "1001", "管理学": "1202", "艺术学": "1301",
    }

    for idx, (major, category, subjects, base_line, is_mba) in enumerate(MAJORS):
        code = category_code.get(category, "0101") + f"{idx % 100:02d}"
        is_hot = major in HOT_MAJORS
        is_cold = major in COLD_MAJORS
        for school, province, city, tier in UNIVERSITIES:
            lo, hi, ratio_base, enroll_lo, enroll_hi, prob = TIER[tier]
            # 热门专业保证在主流院校（985/211/双一流）中一定开设，
            # 避免「杭州电子科技大学没有计算机」这类违背常识的缺失；
            # 其余情况按「层次概率 × 专业热度系数」筛选，控制文件规模。
            if is_hot and (tier in ("985", "211", "双一流") or school in STRONG_DOUBLE_NON):
                pass  # 强制入选
            elif is_cold:
                if random.random() > prob * 0.5:
                    continue
            else:
                if random.random() > prob:
                    continue

            # 分数：层次加成 + 专业热度加成 + 小幅波动
            add = random.randint(lo, hi)
            heat_bonus = 55 if major in (
                "计算机科学与技术", "软件工程", "电子信息", "网络空间安全",
                "人工智能", "大数据技术与工程", "集成电路工程", "控制科学与工程",
                "通信与信息系统", "金融学", "金融专硕", "会计专硕",
                "法律硕士(非法学)", "教育学", "应用心理", "新闻与传播", "临床医学",
            ) else (30 if major in (
                "法学", "会计学", "工商管理", "应用经济学", "哲学",
                "数学", "应用数学", "中国语言文学", "设计学", "药学",
                "机械工程", "土木工程", "车辆工程", "内科学", "外科学",
            ) else 8)
            line = base_line + add + heat_bonus
            mean = line + random.randint(6, 16 if not is_mba else 22)

            # 报录比：层次 + 专业热度 + 波动
            ratio = ratio_base + random.uniform(-1.5, 3.0)
            if major in HOT_MAJORS:
                ratio += 3.0
            ratio = max(1.5, round(ratio, 1))

            enroll = random.randint(enroll_lo, enroll_hi)
            star = difficulty(line - base_line - heat_bonus, tier)

            rows.append({
                "学校": school, "省份": province, "城市": city, "层次": tier,
                "专业": major, "专业代码": code, "门类": category,
                "初试科目": subjects, "复试线": line, "录取均分": mean,
                "报录比": ratio, "招生人数": enroll, "难度": star,
            })

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=header)
        writer.writeheader()
        writer.writerows(rows)

    provinces = sorted({u[1] for u in UNIVERSITIES})
    tiers = {}
    for u in UNIVERSITIES:
        tiers[u[3]] = tiers.get(u[3], 0) + 1
    print(f"生成完成：{len(rows)} 条记录")
    print(f"高校数：{len(UNIVERSITIES)} 所，专业数：{len(MAJORS)} 个，省级地区：{len(provinces)} 个")
    print("层次分布：" + "、".join(f"{k} {v} 所" for k, v in sorted(tiers.items())))


if __name__ == "__main__":
    generate()
